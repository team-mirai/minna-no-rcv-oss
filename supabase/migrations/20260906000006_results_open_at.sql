-- 結果公開時刻（results_open_at）
--
-- 締切（close_at）＝受付をやめる時刻、結果公開（results_open_at）＝結果を見せる時刻。
-- これまでは締切がそのまま結果公開のトリガーだったため、「18時に締め切って、20時の配信で
-- 発表したい」ができなかった（締切と同時に、参加URLを知っている人なら誰でも結果ページと
-- プレゼンモードを開けた）。この列で 2 つの時刻を分ける。
--
-- null = これまでどおり「締切と同時に公開」。既存の poll は null なので挙動は変わらない。
--
-- 受付の締切（submit_ballot / close_poll）とは独立で、この列は受理には一切影響しない。
-- 結果を見せてよいかの判定はアプリ側（src/lib/closeAt.ts の isResultsOpen）で行う。
-- 参加者はアプリ経由でしか読めない（全テーブル RLS 有効・ポリシー無し＝ service_role のみ）
-- ので、これで「締切後・公開前は誰にも見せない」を満たせる。
alter table poll add column results_open_at timestamptz;
